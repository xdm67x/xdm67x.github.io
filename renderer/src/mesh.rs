//! Procedural mesh generation.
//!
//! Every shape in the world is built here on the CPU at load time, then drawn
//! instanced: five meshes cover the whole site.
//!
//!   - `shard`       the glass plate the structure is made of
//!   - `torus`       the hairline rings
//!   - `sphere`      the core and the signal
//!
//! Meshes are authored in world units and instanced; instances carry a full
//! matrix, so a shard can be wide, squat or sliver-shaped without a new mesh.

use glam::{Vec2, Vec3};
use std::f32::consts::{FRAC_PI_2, TAU};

#[repr(C)]
#[derive(Clone, Copy, bytemuck::Pod, bytemuck::Zeroable)]
pub struct Vertex {
    pub pos: [f32; 3],
    pub nrm: [f32; 3],
    /// Vertex tint. `rgb` is always white; `a` carries soft-edge gradients.
    pub col: [f32; 4],
    pub uv: [f32; 2],
}

impl Vertex {
    fn new(pos: Vec3, nrm: Vec3, alpha: f32, uv: Vec2) -> Self {
        Self {
            pos: pos.to_array(),
            nrm: nrm.to_array(),
            col: [1.0, 1.0, 1.0, alpha],
            uv: uv.to_array(),
        }
    }

    /// Vertex buffer layout for the mesh vertex stream (locations 0-3).
    pub const fn layout() -> wgpu::VertexBufferLayout<'static> {
        const ATTRS: [wgpu::VertexAttribute; 4] = wgpu::vertex_attr_array!(
            0 => Float32x3, // position
            1 => Float32x3, // normal
            2 => Float32x4, // tint + soft-edge alpha
            3 => Float32x2, // uv
        );
        wgpu::VertexBufferLayout {
            array_stride: std::mem::size_of::<Vertex>() as wgpu::BufferAddress,
            step_mode: wgpu::VertexStepMode::Vertex,
            attributes: &ATTRS,
        }
    }
}

#[derive(Default, Clone)]
pub struct MeshData {
    pub vertices: Vec<Vertex>,
    pub indices: Vec<u32>,
}

impl MeshData {
    fn push_quad(&mut self, a: u32, b: u32, c: u32, d: u32) {
        self.indices.extend_from_slice(&[a, b, c, a, c, d]);
    }
}

/// One axis of samples for a rounded shape: dense along the rounded ends,
/// even across the flat middle, always including both extremes.
fn axis_samples(half: f32, r: f32, arc_steps: usize, flat_steps: usize) -> Vec<f32> {
    let flat = (half - r).max(0.0);
    let mut v = Vec::with_capacity(arc_steps * 2 + flat_steps + 1);
    for i in 0..=arc_steps {
        let a = (1.0 - i as f32 / arc_steps as f32) * FRAC_PI_2;
        v.push(-flat - r * a.sin());
    }
    for i in 1..flat_steps.max(2) {
        let t = i as f32 / flat_steps.max(2) as f32;
        v.push(-flat + 2.0 * flat * t);
    }
    for i in 0..=arc_steps {
        let a = (i as f32 / arc_steps as f32) * FRAC_PI_2;
        v.push(flat + r * a.sin());
    }
    v
}

/// A box with rounded edges and corners, generated by projecting the surface
/// of the outer box onto a sphere-swept inner box. Normals are exact and
/// smooth across every bevel.
pub fn rounded_box(
    hx: f32,
    hy: f32,
    hz: f32,
    radius: f32,
    arc_steps: usize,
    flat_steps: usize,
) -> MeshData {
    let r = radius.max(0.0005).min(hx).min(hy).min(hz);
    let halves = [hx, hy, hz];
    let samples = [
        axis_samples(hx, r, arc_steps, flat_steps),
        axis_samples(hy, r, arc_steps, flat_steps),
        axis_samples(hz, r, arc_steps, flat_steps),
    ];
    let inner = Vec3::new(hx - r, hy - r, hz - r);

    let mut m = MeshData::default();
    for face in 0..6 {
        let axis = face / 2;
        let sign = if face % 2 == 0 { 1.0 } else { -1.0 };
        let (u_axis, v_axis) = match axis {
            0 => (1usize, 2usize),
            1 => (2, 0),
            _ => (0, 1),
        };
        let us = &samples[u_axis];
        let vs = &samples[v_axis];
        let base = m.vertices.len() as u32;
        let w = us.len();

        for (j, vv) in vs.iter().enumerate() {
            for (i, uu) in us.iter().enumerate() {
                let mut p = Vec3::ZERO;
                p[axis] = sign * halves[axis];
                p[u_axis] = *uu;
                p[v_axis] = *vv;
                let q = p.clamp(-inner, inner);
                let d = p - q;
                let n = if d.length_squared() > 1e-12 {
                    d.normalize()
                } else {
                    let mut f = Vec3::ZERO;
                    f[axis] = sign;
                    f
                };
                let uv = Vec2::new(i as f32 / (w - 1) as f32, j as f32 / (vs.len() - 1) as f32);
                m.vertices.push(Vertex::new(q + n * r, n, 1.0, uv));
            }
        }

        let mut outward = Vec3::ZERO;
        outward[axis] = sign;
        let p00 = Vec3::from(m.vertices[base as usize].pos);
        let p10 = Vec3::from(m.vertices[base as usize + 1].pos);
        let p01 = Vec3::from(m.vertices[base as usize + w].pos);
        let flip = (p10 - p00).cross(p01 - p00).dot(outward) < 0.0;

        for j in 0..vs.len() - 1 {
            for i in 0..us.len() - 1 {
                let a = base + (j * w + i) as u32;
                let b = a + 1;
                let d = a + w as u32;
                let c = d + 1;
                if flip {
                    m.push_quad(a, d, c, b);
                } else {
                    m.push_quad(a, b, c, d);
                }
            }
        }
    }
    m
}

/// Convenience: a sphere expressed through the rounded box (r == half extent).
pub fn sphere(radius: f32, steps: usize) -> MeshData {
    rounded_box(radius, radius, radius, radius, steps, 2)
}

/// A broken-edged glass plate, facing +Z, with a circumradius of 1.
///
/// The rim is a three-ring bevel — face, edge, face — so the outline catches a
/// bright specular line exactly the way a chipped pane of glass does. The
/// outline itself is a polygon with a fixed wobble, which is what stops the
/// field of plates from reading as a tiled pattern.
pub fn shard(sides: usize, irregularity: f32, thickness: f32) -> MeshData {
    let sides = sides.max(3);
    let step = TAU / sides as f32;
    let half = thickness * 0.5;
    // Pulled in slightly at the faces, so the rim is a bevel rather than a
    // vertical wall.
    let face_inset = 0.22;

    let mut radii = Vec::with_capacity(sides);
    let mut angles = Vec::with_capacity(sides);
    for k in 0..sides {
        // Two incommensurate waves: a stable, non-repeating silhouette.
        let wobble = (k as f32 * 1.0).sin() * 0.55 + (k as f32 * 2.37).cos() * 0.45;
        radii.push(1.0 - irregularity * (0.5 + 0.5 * wobble));
        angles.push(k as f32 * step + irregularity * 0.45 * step * (k as f32 * 1.7).sin());
    }

    // Three rings of the same outline: top face rim, sharp edge, bottom face rim.
    let rings: [(f32, f32); 3] = [
        (half, 1.0 - face_inset),
        (0.0, 1.0),
        (-half, 1.0 - face_inset),
    ];

    let mut m = MeshData::default();
    for (z, radius_scale) in rings {
        for k in 0..sides {
            let r = radii[k] * radius_scale;
            let (s, c) = angles[k].sin_cos();
            let radial = Vec3::new(c, s, 0.0);
            // The rim leans into the bevel; the middle ring is purely radial.
            let nrm = if z == 0.0 {
                radial
            } else {
                (radial * 0.42 + Vec3::Z * (z.signum() * 1.0)).normalize()
            };
            m.vertices.push(Vertex::new(
                radial * r + Vec3::Z * z,
                nrm,
                1.0,
                Vec2::new(c * 0.5 + 0.5, s * 0.5 + 0.5),
            ));
        }
    }

    // The two faces: a fan to a centre vertex, so the plate is closed.
    let centre_top = m.vertices.len() as u32;
    m.vertices
        .push(Vertex::new(Vec3::Z * half, Vec3::Z, 1.0, Vec2::splat(0.5)));
    let centre_bottom = m.vertices.len() as u32;
    m.vertices.push(Vertex::new(
        Vec3::Z * -half,
        -Vec3::Z,
        1.0,
        Vec2::splat(0.5),
    ));

    let top = 0u32;
    let mid = sides as u32;
    let bottom = (sides * 2) as u32;

    for k in 0..sides as u32 {
        let next = (k + 1) % sides as u32;
        m.indices
            .extend_from_slice(&[centre_top, top + k, top + next]);
        m.indices
            .extend_from_slice(&[centre_bottom, bottom + next, bottom + k]);
        m.push_quad(top + k, mid + k, mid + next, top + next);
        m.push_quad(mid + k, bottom + k, bottom + next, mid + next);
    }

    m
}

/// Torus lying in the XZ plane (axis = +Y).
pub fn torus(radius: f32, tube: f32, radial_segments: usize, tube_segments: usize) -> MeshData {
    let mut m = MeshData::default();
    for i in 0..=radial_segments {
        let th = i as f32 / radial_segments as f32 * TAU;
        let (st, ct) = th.sin_cos();
        let radial = Vec3::new(ct, 0.0, st);
        for j in 0..=tube_segments {
            let ph = j as f32 / tube_segments as f32 * TAU;
            let (sp, cp) = ph.sin_cos();
            let n = radial * cp + Vec3::Y * sp;
            let p = radial * radius + n * tube;
            m.vertices.push(Vertex::new(
                p,
                n,
                1.0,
                Vec2::new(
                    i as f32 / radial_segments as f32,
                    j as f32 / tube_segments as f32,
                ),
            ));
        }
    }
    let stride = (tube_segments + 1) as u32;
    for i in 0..radial_segments as u32 {
        for j in 0..tube_segments as u32 {
            let a = i * stride + j;
            m.push_quad(a, a + stride, a + stride + 1, a + 1);
        }
    }
    m
}
